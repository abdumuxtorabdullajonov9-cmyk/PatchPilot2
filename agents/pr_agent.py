import os
import time

from dotenv import load_dotenv
from github import Github

load_dotenv()


def open_pull_request_multi(repo_full_name: str, files: dict, title: str, body: str,
                            branch_name: str = None) -> str:
    """Bitta branch va BITTA Pull Request ichida bir nechta faylni yangilaydi."""
    gh = Github(os.environ["GITHUB_TOKEN"])
    repo = gh.get_repo(repo_full_name)
    base_branch = repo.default_branch
    if branch_name is None:
        branch_name = f"patchpilot-fix-{int(time.time())}"

    base = repo.get_branch(base_branch)
    repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=base.commit.sha)

    for path, content in files.items():
        existing = repo.get_contents(path, ref=branch_name)
        repo.update_file(
            path=path,
            message=f"PatchPilot: fix security issues in {path}",
            content=content,
            sha=existing.sha,
            branch=branch_name,
        )

    pr = repo.create_pull(title=title, body=body, head=branch_name, base=base_branch)
    return pr.html_url


def open_pull_request(repo_full_name: str, file_relative_path: str, fixed_code: str,
                      branch_name: str = None, base_branch: str = None) -> str:
    """Eski chaqiruvlar (main.py) uchun: bitta fayl."""
    return open_pull_request_multi(
        repo_full_name,
        {file_relative_path: fixed_code},
        title=f"PatchPilot: automated security fix for {file_relative_path}",
        body="This PR was automatically generated by PatchPilot.",
        branch_name=branch_name,
    )